package CursoHoraCodarJava.EstruturaRepeticao;

public class EstruturaDoWhile {
    public static void main(String[] args) {
        // O do while é uma estrutura de repetição com teste no final.
        // O código executa pelo menos uma vez, mesmo que a condição seja falsa

        int j = 10;
        do {
            System.out.println("O valor de j e:" + j);
            j--;
        }while(j>0);


        
    }

}
