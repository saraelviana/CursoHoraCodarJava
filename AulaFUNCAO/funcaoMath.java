public class funcaoMath {
    public static void main(String[] args) {
        // Math é uma classe nativa do Java que fornece métodos para realizar operações matemáticas comuns

        System.out.println(Math.sqrt(16)); // Raiz quadrada de 16
        System.out.println(Math.abs(-10)); // Valor absoluto
        System.out.println(Math.pow(2, 3)); // 2 elevado a 3
        System.out.println(Math.max(5, 10)); // Maior valor entre 5 e 10
        System.out.println(Math.min(5, 10)); // Menor valor entre 5 e 10
        System.out.println(Math.random()); // Número aleatório entre 0.0 e 1.0


        
    }

}
